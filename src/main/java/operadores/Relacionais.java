package operadores;

public class Relacionais {

    public static void main(String[] args) {

        System.out.println(3>2);
        System.out.println(3<2);
        System.out.println(3>=2);
        System.out.println(3<=2);
        System.out.println(3!=2);
        System.out.println(3==2);

    }

}
